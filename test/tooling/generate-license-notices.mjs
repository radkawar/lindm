// Collect original, complete redistribution texts; never synthesize upstream grants.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const assets = join(root, "internal/packaging/assets");
const entries = [];
const upstreamTexts = JSON.parse(
  await readFile(join(root, "test/tooling/upstream-license-texts.json"), "utf8"),
);
const licenseName = /^(?:licen[cs]e|copying|notice|copyright|ofl)(?:[._-].*)?$/i;
async function collect(directory, identity, source, extra = []) {
  const found = [];
  async function walk(path) {
    for (const entry of (await readdir(path, { withFileTypes: true })).sort((a, b) =>
      a.name.localeCompare(b.name, "en"),
    )) {
      if (["node_modules", ".git"].includes(entry.name)) continue;
      const absolute = join(path, entry.name);
      if (entry.isDirectory()) await walk(absolute);
      else if (entry.isFile() && licenseName.test(entry.name)) {
        const text = await readFile(absolute, "utf8");
        if (!text.trim()) throw new Error(`${identity}: empty license ${absolute}`);
        found.push({ file: relative(directory, absolute).replaceAll("\\", "/"), text });
      } else if (entry.isFile() && /\.(?:m?js|tsx?)$/.test(entry.name)) {
        // Some npm publications omit LICENSE but retain copyright/license
        // comments, including protobuf's complete Google BSD-3-Clause grant.
        const text = await readFile(absolute, "utf8");
        const header = text.match(/^(?:(?:\/\/[^\n]*\n)+|\/\*[\s\S]*?\*\/)/)?.[0];
        if (header && /copyright/i.test(header)) {
          found.push({
            file: relative(directory, absolute).replaceAll("\\", "/") + " (leading notice)",
            text: header,
          });
        }
      }
    }
  }
  await walk(directory);
  const legalFiles = found.filter((item) => !item.file.endsWith("(leading notice)"));
  if (legalFiles.length === 0 && extra.length === 0) {
    throw new Error(`${identity}: missing full upstream license text`);
  }
  const seen = new Set();
  for (const item of [...found, ...extra]) {
    if (seen.has(item.text)) continue;
    seen.add(item.text);
    entries.push({ identity, source, ...item });
  }
}
const products = ["lindmd", "lindm-agent", "lindmctl", "lindm-recovery-build", "lindm-install"];
// Cover both Linux artifact architectures, including the exported installer.
const graph = ["amd64", "arm64"]
  .map((architecture) =>
    execFileSync(
      "go",
      [
        "list",
        "-mod=readonly",
        "-deps",
        "-f",
        "{{with .Module}}{{.Path}}{{end}}",
        ...products.map((p) => `./cmd/${p}`),
      ],
      {
        cwd: root,
        encoding: "utf8",
        env: { ...process.env, GOOS: "linux", GOARCH: architecture, CGO_ENABLED: "0" },
      },
    ),
  )
  .join("\n");
const selected = new Set(graph.split("\n").filter((p) => p && p !== "lindm"));
const modules = execFileSync(
  "go",
  ["list", "-m", "-f", "{{.Path}}\t{{.Version}}\t{{.Dir}}", "all"],
  {
    cwd: root,
    encoding: "utf8",
  },
)
  .trim()
  .split("\n")
  .map((line) => line.split("\t"));
for (const [path, version, directory] of modules) {
  if (!selected.has(path)) continue;
  if (!directory) throw new Error(`${path}: download pinned module before collecting licenses`);
  await collect(directory, `Go module ${path}@${version}`, `https://${path}`);
}
const goroot = execFileSync("go", ["env", "GOROOT"], { cwd: root, encoding: "utf8" }).trim();
const goVersion = execFileSync("go", ["env", "GOVERSION"], { cwd: root, encoding: "utf8" }).trim();
for (const name of ["LICENSE", "PATENTS"]) {
  entries.push({
    identity: `Go toolchain and standard library ${goVersion}`,
    source: "https://go.dev/",
    file: name,
    text: await readFile(join(goroot, name), "utf8"),
  });
}
const lock = JSON.parse(await readFile(join(root, "package-lock.json"), "utf8"));
for (const [path, pkg] of Object.entries(lock.packages)) {
  if (!path || pkg.dev === true) continue;
  await collect(
    join(root, path),
    `npm package ${path.replace(/^node_modules\//, "")}@${pkg.version}`,
    pkg.resolved ?? "package-lock.json",
    upstreamTexts[`${path}@${pkg.version}`] ?? [],
  );
}
for (const path of [
  "web/LICENSE.shadcn",
  "web/LICENSE.fonts",
  "docs/brand/Inter-LICENSE.txt",
  "internal/agent/desktop/keysymdata/LICENSE",
]) {
  entries.push({
    identity: "Copied source or bundled font",
    source: path,
    file: path,
    text: await readFile(join(root, path), "utf8"),
  });
}
entries.sort(
  (a, b) => a.identity.localeCompare(b.identity, "en") || a.file.localeCompare(b.file, "en"),
);
const output = [
  "THIRD-PARTY REDISTRIBUTION TEXTS",
  "Generated by test/tooling/generate-license-notices.mjs from pinned dependencies.",
  "Selection: conservative package graph of shipped Go products and non-dev npm lock graph.",
  "Original complete files follow; individual upstream terms remain controlling.",
  "",
];
for (const entry of entries) {
  const hash = createHash("sha256").update(entry.text).digest("hex");
  output.push(
    "=".repeat(72),
    entry.identity,
    `Source: ${entry.source}`,
    `Original file: ${entry.file}`,
    `SHA-256 (UTF-8 text): ${hash}`,
    "",
    entry.text,
    "",
  );
}
await writeFile(join(assets, "THIRD-PARTY-LICENSES"), output.join("\n"));
for (const name of ["LICENSE", "NOTICE"]) {
  await writeFile(join(assets, name), await readFile(join(root, name)));
}
