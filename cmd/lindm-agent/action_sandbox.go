const actionDropInDirectory = "/etc/systemd/system/lindm-executor.service.d"
const actionDropInName = "50-device-actions.conf"

// actionSandboxCommand resolves local qualified target identities before exposing
// their exact device nodes. It never opens a target for writing or restarts work.
func actionSandboxCommand(ctx context.Context, args []string, output io.Writer) error {
	if os.Geteuid() != 0 {
		return errors.New("action-sandbox requires root")
	}
	flags := flag.NewFlagSet("action-sandbox", flag.ContinueOnError)
	install := flags.Bool("install", false, "install reviewed per-target systemd drop-in without restarting executor")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return errors.New("action-sandbox accepts only -install")
	}
	doc, err := config.Load(config.ExecutorConfigPath)
	if err != nil {
		return err
	}
	cfg := doc.Proto.GetActionProvider()
	if cfg == nil {
		return errors.New("action_provider must be configured before generating a sandbox exception")
	}
	// Device discovery has no account effects and must not open the executor's
	// live journal. Retain the original qualification for the emitted sandbox.
	discovery := proto.CloneOf(cfg)
	discovery.AllowAccountLock = false
	discovery.LocalAdminAccounts = nil
	provider, err := nativeActionProvider(discovery, nil)
	if err != nil {
		return err
	}
	devices, err := provider.SandboxDevices(ctx)
	if err != nil {
		return err
	}
	if len(cfg.GetTargets()) != 0 {
		var stat unix.Stat_t
		if err := unix.Lstat("/dev/mapper/control", &stat); err != nil {
			return fmt.Errorf("inspect mapper control: %w", err)
		}
		if stat.Mode&unix.S_IFMT != unix.S_IFCHR {
			return errors.New("mapper control is not a character device")
		}
		devices = append(devices, "/dev/mapper/control")
	}
	var recoveryPaths string
	if cfg.GetAllowRecoveryHandoff() {
		recoveryBoot := doc.Proto.GetRecoveryBoot()
		recoveryPaths, err = recoverySandboxPaths(recoveryBoot)
		if err != nil {
			return err
		}
		if recoveryBoot.GetCustody() == agentv1.RecoveryCustody_RECOVERY_CUSTODY_TPM {
			var stat unix.Stat_t
			if err := unix.Lstat("/dev/tpmrm0", &stat); err != nil {
				return fmt.Errorf("inspect TPM resource manager: %w", err)
			}
			if stat.Mode&unix.S_IFMT != unix.S_IFCHR {
				return errors.New("TPM resource manager is not a character device")
			}
			devices = append(devices, "/dev/tpmrm0")
		}
		if recoveryBoot.GetBootMode() == agentv1.RecoveryBootMode_RECOVERY_BOOT_MODE_MEASURED_GRUB {
			measured, err := measuredBootDevices()
			if err != nil {
				return err
			}
			devices = append(devices, measured...)
		}
	}
	content, err := actionSandboxText(cfg, devices)
	if err != nil {
		return err
	}
	content += recoveryPaths
	if !*install {
		_, err := io.WriteString(output, content)
		return err
	}
	if err := installActionDropIn(content); err != nil {
		return err
	}
	_, err = io.WriteString(output, "Installed "+actionDropInDirectory+"/"+actionDropInName+"; reload systemd and restart lindm-executor explicitly.\n")
	return err
}

func actionSandboxText(cfg *agentv1.DeviceActionProviderConfig, devices []string) (string, error) {
	var text strings.Builder
	text.WriteString("# Generated by root-only lindm-agent action-sandbox from qualified local identities.\n[Service]\nPrivateDevices=yes\nDevicePolicy=closed\n")
	// These retain the existing native service worker's root namespace/file
	// ownership operations; action capabilities are added individually below.
	text.WriteString("CapabilityBoundingSet=\nCapabilityBoundingSet=CAP_CHOWN CAP_DAC_OVERRIDE CAP_DAC_READ_SEARCH CAP_FOWNER CAP_KILL CAP_SETGID CAP_SETUID CAP_SYS_ADMIN CAP_SYS_CHROOT")
	if actionMemoryRequired(cfg) {
		text.WriteString(" CAP_IPC_LOCK")
	}
	if cfg.GetAllowQuarantine() {
		text.WriteString(" CAP_NET_ADMIN")
	}
	text.WriteString("\nRestrictAddressFamilies=\nRestrictAddressFamilies=AF_UNIX")
	if cfg.GetAllowQuarantine() {
		text.WriteString(" AF_NETLINK")
	}
	text.WriteString("\n")
	if actionMemoryRequired(cfg) {
		text.WriteString("LimitMEMLOCK=infinity\n")
	}
	if cfg.GetAllowAccountLock() || len(cfg.GetLocalAdminAccounts()) != 0 {
		// Shadow tools atomically rename files and create their native locks/
		// backups in /etc; file-only writable bind mounts break that protocol.
		// This exception is provisioned only by root's explicit account opt-in
		// or managed local-admin allowlist.
		text.WriteString("ReadWritePaths=/etc\n")
	}
	devices = slices.Clone(devices)
	slices.Sort(devices)
	for _, device := range slices.Compact(devices) {
		if !strings.HasPrefix(device, "/dev/") || filepath.Clean(device) != device {
			return "", errors.New("resolved device path cannot be represented safely in systemd")
		}
		for _, character := range device {
			if (character < 'a' || character > 'z') && (character < 'A' || character > 'Z') && (character < '0' || character > '9') && !strings.ContainsRune("/._-", character) {
				return "", errors.New("resolved device path contains systemd metacharacters")
			}
		}
		text.WriteString("BindPaths=" + device + "\nDeviceAllow=" + device + " rw\n")
	}
	return text.String(), nil
}

func installActionDropIn(content string) (err error) {
	// Every ancestor must already be root-owned and non-writable to other users.
	for _, path := range []string{"/", "/etc", "/etc/systemd", "/etc/systemd/system"} {
		if err := checkedSystemdDirectory(path); err != nil {
			return err
		}
	}
	if err := os.Mkdir(actionDropInDirectory, 0755); err != nil && !errors.Is(err, os.ErrExist) {
		return err
	}
	if err := checkedSystemdDirectory(actionDropInDirectory); err != nil {
		return err
	}
	root, err := os.OpenRoot(actionDropInDirectory)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	temporary := ".device-actions-" + uuid.NewString()
	file, err := root.OpenFile(temporary, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			err = errors.Join(err, root.Remove(temporary))
		}
	}()
	_, writeErr := io.WriteString(file, content)
	err = errors.Join(writeErr, file.Sync(), file.Close())
	if err != nil {
		return err
	}
	if err := root.Rename(temporary, actionDropInName); err != nil {
		return err
	}
	directory, err := os.Open(actionDropInDirectory)
	if err != nil {
		return err
	}
	return errors.Join(directory.Sync(), directory.Close())
}

func checkedSystemdDirectory(path string) error {
	var stat unix.Stat_t
	if err := unix.Lstat(path, &stat); err != nil {
		return err
	}
	if !custody.TrustedDirectory(&stat) {
		return errors.New("systemd drop-in ancestry must satisfy privileged directory custody")
	}
	return nil
}
