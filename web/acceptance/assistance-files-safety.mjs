import { constants } from "node:fs";
import { open } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";

const fixtureName = /^lindm-file-[a-f0-9]{24}\.txt$/;
const uuid = /^[a-f0-9]{8}-[a-f0-9]{4}-[1-5][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/;
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function bounded(promise, milliseconds, reason) {
  let timer;
  try {
    return await Promise.race([
      promise,
      new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error(reason)), milliseconds);
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

async function fixture(directory, name, pdf) {
  if (!fixtureName.test(name ?? "")) throw new Error("invalid_hostile_fixture_name");
  const path = resolve(directory, name);
  if (dirname(path) !== directory) throw new Error("invalid_hostile_fixture_path");
  const file = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW);
  try {
    const before = await file.stat();
    if (
      !before.isFile() ||
      before.size !== 512 ||
      before.uid !== process.getuid() ||
      before.mode & 0o077
    )
      throw new Error("private_exact_512_byte_fixture_required");
    const data = Buffer.alloc(512);
    let offset = 0;
    while (offset < data.length) {
      const { bytesRead } = await file.read(data, offset, data.length - offset, offset);
      if (!bytesRead) throw new Error("hostile_fixture_short_read");
      offset += bytesRead;
    }
    const after = await file.stat();
    if (
      before.dev !== after.dev ||
      before.ino !== after.ino ||
      before.size !== after.size ||
      before.mtimeMs !== after.mtimeMs ||
      before.ctimeMs !== after.ctimeMs
    )
      throw new Error("hostile_fixture_changed");
    if (
      pdf
        ? !data.subarray(0, 9).equals(Buffer.from("%PDF-1.7\n"))
        : !data.every((value) => value === 10 || (value >= 32 && value <= 126))
    )
      throw new Error("hostile_fixture_content_invalid");
    const sha256 = digest(data);
    return {
      path,
      sha256,
      metadata: {
        name,
        size: "512",
        mimeType: "text/plain",
        sha256: Buffer.from(sha256, "hex").toString("base64"),
      },
    };
  } finally {
    await file.close();
  }
}

function sameMetadata(actual, expected) {
  return (
    actual &&
    Object.keys(actual).length === 4 &&
    actual.name === expected.name &&
    actual.size === expected.size &&
    actual.mimeType === expected.mimeType &&
    actual.sha256 === expected.sha256
  );
}

// The six templates are generated by Go protobuf from independently reread host
// files, not by a handwritten wire codec. The wrapper compares whole real frames
// before changing only outbound bytes. Incoming messages and native send calls
// are observed, never replaced, acknowledged or suppressed.
function installWireProbe({ requestId, outbound, inbound }) {
  if (window.__lindmFileSafetyProbe) throw new Error("hostile_probe_already_installed");
  const channels = (window.__lindmLabPeers ?? [])
    .flatMap((peer) => peer.inputs)
    .filter((channel) => channel.label === "lindm-files" && channel.readyState === "open");
  if (channels.length !== 1) throw new Error("single_real_file_channel_required");
  const channel = channels[0];
  if (!channel.ordered || channel.maxRetransmits !== null || channel.maxPacketLifeTime !== null)
    throw new Error("reliable_ordered_file_channel_required");
  const descriptor = Object.getOwnPropertyDescriptor(channel, "send");
  const nativeSend = channel.send;
  const state = {
    requestId,
    outbound: [],
    inbound: [],
    failure: "",
    channelLabel: channel.label,
    ordered: channel.ordered,
    reliable: channel.maxRetransmits === null && channel.maxPacketLifeTime === null,
    restored: false,
  };
  const bytes = (data) => {
    if (data instanceof ArrayBuffer) return new Uint8Array(data);
    if (ArrayBuffer.isView(data))
      return new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
    throw new Error("unexpected_file_frame_type");
  };
  const equal = (a, b) => a.length === b.length && a.every((value, index) => value === b[index]);
  const fail = (reason) => {
    if (!state.failure) state.failure = reason;
  };
  const receive = (event) => {
    try {
      const original = bytes(event.data);
      const expected = inbound[state.inbound.length];
      if (!expected || !equal(original, expected.data))
        throw new Error("unexpected_incoming_receiver_frame");
      state.inbound.push({ kind: expected.kind, data: Array.from(original) });
    } catch (error) {
      fail(error.message);
    }
  };
  const replacedSend = function (data) {
    try {
      const original = bytes(data);
      const expected = outbound[state.outbound.length];
      if (this !== channel || !expected || !equal(original, expected.original)) {
        fail("unexpected_outgoing_carrier_frame");
        // Unexpected traffic is not hidden from the product. The probe fails.
        return nativeSend.call(this, data);
      }
      const forwarded = Uint8Array.from(expected.forwarded);
      nativeSend.call(channel, forwarded);
      state.outbound.push({
        kind: expected.kind,
        original: Array.from(original),
        forwarded: Array.from(forwarded),
      });
    } catch (error) {
      fail(error.message);
      throw error;
    }
  };
  const restore = () => {
    channel.removeEventListener("message", receive);
    if (descriptor) Object.defineProperty(channel, "send", descriptor);
    else delete channel.send;
    if (channel.send !== nativeSend) throw new Error("hostile_send_restore_failed");
    state.restored = true;
    delete window.__lindmFileSafetyProbe;
  };
  try {
    Object.defineProperty(channel, "send", {
      configurable: true,
      writable: true,
      value: replacedSend,
    });
    channel.addEventListener("message", receive);
    Object.defineProperty(window, "__lindmFileSafetyProbe", {
      configurable: true,
      value: { state, restore },
    });
  } catch (error) {
    restore();
    throw error;
  }
}

export function createAssistanceFileSafetyCommands(context) {
  let active = null;

  async function restore() {
    const current = active;
    if (!current) return { restored: true };
    const errors = [];
    clearTimeout(current.watchdog);
    try {
      await current.page.evaluate(() => window.__lindmFileSafetyProbe?.restore());
    } catch (error) {
      errors.push(error);
    }
    try {
      await current.page.unroute(current.url, current.routeHandler);
    } catch (error) {
      errors.push(error);
    }
    current.page.off("response", current.responseHandler);
    if (current.heldRoute) {
      try {
        await current.heldRoute.abort("aborted");
      } catch (error) {
        errors.push(error);
      }
      current.heldRoute = null;
    }
    current.release.resolve();
    if (errors.length) throw new AggregateError(errors, "hostile_probe_restore_failed");
    active = null;
    return { restored: true };
  }

  async function failWithRestore(error) {
    try {
      await restore();
    } catch (cleanup) {
      throw new AggregateError([error, cleanup], "hostile_probe_and_restore_failed");
    }
    throw error;
  }

  return {
    async fileSafetyReceiverPrepare(args) {
      if (active) throw new Error("hostile_probe_already_active");
      const directory = context.evidenceDirectory();
      const carrier = await fixture(directory, args.carrier, false);
      const payload = await fixture(directory, args.payload, true);
      if (
        carrier.path === payload.path ||
        carrier.sha256 === payload.sha256 ||
        !uuid.test(args.sessionId ?? "")
      )
        throw new Error("distinct_hostile_fixture_pair_required");
      const actor = await context.identity();
      const page = context.driver().page;
      const authority = context.commandAuthority();
      const sessionId = /\/assistance\/([0-9a-f-]{36})$/.exec(new URL(page.url()).pathname)?.[1];
      if (
        sessionId !== args.sessionId ||
        !authority.url?.endsWith("/RunAssistanceCommand") ||
        !authority.csrf
      )
        throw new Error("authenticated_file_authority_required");
      const url = authority.url.replace(/\/RunAssistanceCommand$/, "/StartAssistanceFileTransfer");
      const current = {
        page,
        url,
        sessionId,
        actor,
        carrier,
        payload,
        original: null,
        forwarded: null,
        captured: Promise.withResolvers(),
        started: Promise.withResolvers(),
        terminal: Promise.withResolvers(),
        release: Promise.withResolvers(),
        heldRoute: null,
        forwards: 0,
        failure: "",
        requestId: "",
      };
      active = current;
      current.routeHandler = async (route) => {
        try {
          const request = route.request();
          const body = request.postDataJSON();
          if (
            current.original ||
            request.method() !== "POST" ||
            request.headers()["x-csrf-token"] !== authority.csrf ||
            body.sessionId !== sessionId ||
            !uuid.test(body.transfer?.requestId ?? "") ||
            body.transfer.direction !== "ASSISTANCE_FILE_DIRECTION_TO_USER" ||
            Object.keys(body).length !== 2 ||
            Object.keys(body.transfer).length !== 3 ||
            !sameMetadata(body.transfer.file, carrier.metadata)
          ) {
            current.failure = "unexpected_start_rpc";
            await route.continue();
            current.captured.resolve();
            return;
          }
          current.original = body;
          current.requestId = body.transfer.requestId;
          current.heldRoute = route;
          current.captured.resolve();
          await current.release.promise;
        } catch (error) {
          current.failure = error.message;
          try {
            await route.abort("aborted");
          } catch (cleanup) {
            current.failure = new AggregateError(
              [error, cleanup],
              "hostile_route_restore_failed",
            ).message;
          }
          current.captured.resolve();
        }
      };
      current.responseHandler = async (response) => {
        if (
          !/\/(StartAssistanceFileTransfer|GetAssistanceFileTransfer|CancelAssistanceFileTransfer)$/.test(
            new URL(response.url()).pathname,
          )
        )
          return;
        try {
          const request = response.request().postDataJSON();
          const requestId = request.transfer?.requestId ?? request.requestId;
          if (
            !current.requestId ||
            request.sessionId !== sessionId ||
            requestId !== current.requestId
          )
            return;
          if (!response.ok()) throw new Error("hostile_rpc_response_failed");
          const body = await response.json();
          if (body.transfer?.requestId !== current.requestId)
            throw new Error("hostile_report_identity_mismatch");
          if (response.url() === url) current.started.resolve(body.transfer);
          if (
            [
              4,
              5,
              6,
              7,
              "ASSISTANCE_FILE_STATE_SUCCEEDED",
              "ASSISTANCE_FILE_STATE_DENIED",
              "ASSISTANCE_FILE_STATE_CANCELLED",
              "ASSISTANCE_FILE_STATE_FAILED",
            ].includes(body.transfer.state)
          )
            current.terminal.resolve(body.transfer);
        } catch (error) {
          current.failure = error.message;
          current.started.resolve(null);
          current.terminal.resolve(null);
        }
      };
      page.on("response", current.responseHandler);
      try {
        await page.route(url, current.routeHandler);
        // Deadline cleanup only: never used as native readiness or a pass oracle.
        current.watchdog = setTimeout(() => {
          current.failure = "hostile_probe_deadline";
          void restore().catch((error) => {
            current.failure = error.message;
          });
        }, 120_000);
        await page.getByLabel("File to send", { exact: true }).setInputFiles(carrier.path);
        await Promise.all([
          context.ui().click({ role: "button", text: "Send file" }),
          bounded(current.captured.promise, 30_000, "hostile_start_rpc_not_observed"),
        ]);
        if (current.failure || !current.original)
          throw new Error(current.failure || "hostile_start_rpc_not_observed");
        return {
          requestId: current.requestId,
          sessionId,
          actor,
          metadata: current.original.transfer.file,
          carrierSHA256: carrier.sha256,
          payloadSHA256: payload.sha256,
        };
      } catch (error) {
        return failWithRestore(error);
      }
    },

    async fileSafetyReceiverForward(args) {
      const current = active;
      try {
        if (
          !current ||
          current.failure ||
          args.requestId !== current.requestId ||
          !current.heldRoute ||
          current.forwards
        )
          throw new Error("hostile_forward_identity_invalid");
        const decode = (data) => {
          if (typeof data !== "string" || data.length > 2048)
            throw new Error("hostile_frame_template_unbounded");
          const bytes = Buffer.from(data, "base64");
          if (!bytes.length || bytes.length > 1024 || bytes.toString("base64") !== data)
            throw new Error("hostile_frame_template_invalid");
          return Array.from(bytes);
        };
        if (args.outbound?.length !== 3 || args.inbound?.length !== 2)
          throw new Error("hostile_frame_sequence_invalid");
        const outbound = args.outbound.map((frame, index) => {
          if (frame.kind !== ["start", "chunk", "end"][index])
            throw new Error("hostile_frame_order_invalid");
          return {
            kind: frame.kind,
            original: decode(frame.original),
            forwarded: decode(frame.forwarded),
          };
        });
        const inbound = args.inbound.map((frame, index) => {
          if (frame.kind !== ["ready", "cancel"][index])
            throw new Error("hostile_inbound_order_invalid");
          return { kind: frame.kind, data: decode(frame.data) };
        });
        await current.page.evaluate(installWireProbe, {
          requestId: current.requestId,
          outbound,
          inbound,
        });
        current.forwarded = {
          ...current.original,
          transfer: { ...current.original.transfer, file: current.payload.metadata },
        };
        await current.heldRoute.continue({ postData: JSON.stringify(current.forwarded) });
        current.heldRoute = null;
        current.forwards++;
        current.release.resolve();
        const report = await bounded(
          current.started.promise,
          15_000,
          "hostile_start_response_not_observed",
        );
        if (current.failure || !report)
          throw new Error(current.failure || "hostile_start_response_not_observed");
        return report;
      } catch (error) {
        return failWithRestore(error);
      }
    },

    async fileSafetyReceiverFinish(args) {
      const current = active;
      try {
        if (
          !current ||
          current.failure ||
          args.requestId !== current.requestId ||
          current.forwards !== 1
        )
          throw new Error("hostile_finish_identity_invalid");
        const report = await bounded(
          current.terminal.promise,
          15_000,
          "hostile_terminal_report_not_observed",
        );
        if (
          !report ||
          ![7, "ASSISTANCE_FILE_STATE_FAILED"].includes(report.state) ||
          report.reason !== "file_type_denied"
        )
          throw new Error("hostile_receiver_mime_denial_not_observed");
        await current.page.waitForFunction(
          () => {
            const probe = window.__lindmFileSafetyProbe;
            return probe?.state.failure || probe?.state.inbound.length === 2;
          },
          null,
          { timeout: 15_000 },
        );
        const wire = await current.page.evaluate(() => {
          const probe = window.__lindmFileSafetyProbe;
          if (!probe) throw new Error("hostile_wire_probe_missing");
          return probe.state;
        });
        if (
          current.failure ||
          wire.failure ||
          wire.outbound.length !== 3 ||
          wire.inbound.length !== 2
        )
          throw new Error(current.failure || wire.failure || "hostile_wire_sequence_incomplete");
        const result = {
          requestId: current.requestId,
          sessionId: current.sessionId,
          actor: current.actor,
          carrierSHA256: current.carrier.sha256,
          payloadSHA256: current.payload.sha256,
          rpcOriginal: current.original.transfer.file,
          rpcForwarded: current.forwarded.transfer.file,
          rpcForwards: current.forwards,
          channelLabel: wire.channelLabel,
          ordered: wire.ordered,
          reliable: wire.reliable,
          outbound: wire.outbound.map((frame) => ({
            kind: frame.kind,
            original: Buffer.from(frame.original).toString("base64"),
            forwarded: Buffer.from(frame.forwarded).toString("base64"),
            originalSHA256: digest(Buffer.from(frame.original)),
            forwardedSHA256: digest(Buffer.from(frame.forwarded)),
            originalBytes: frame.original.length,
            forwardedBytes: frame.forwarded.length,
          })),
          inbound: wire.inbound.map((frame) => ({
            kind: frame.kind,
            data: Buffer.from(frame.data).toString("base64"),
            sha256: digest(Buffer.from(frame.data)),
            bytes: frame.data.length,
          })),
        };
        await restore();
        return { ...result, restored: true };
      } catch (error) {
        return failWithRestore(error);
      }
    },

    async fileSafetyReceiverRestore() {
      return restore();
    },
  };
}
