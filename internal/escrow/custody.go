// Package escrow owns server custody of device-escrowed secrets (recovery keys
// and managed local-admin passwords) and of administrator-managed secret
// material: device-to-server RSA-OAEP transport decryption and per-record
// AES-256-GCM envelopes wrapped by the deployment KEK. Each use has its own
// transport and storage domain so ciphertext cannot cross purposes. It does not
// authorize reveal, persist records, or sign durability receipts: callers must
// do those at their transactional domain boundary.
package escrow

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha256"
	"crypto/x509"
	"encoding/hex"
	"errors"
	"fmt"
)

const (
	transportDomain           = "lindm-recovery-transport-v1\x00"
	storageDomain             = "lindm-recovery-storage-v1\x00"
	localAdminTransportDomain = "lindm-local-admin-transport-v1\x00"
	localAdminStorageDomain   = "lindm-local-admin-storage-v1\x00"
	secretStorageDomain       = "lindm-secret-storage-v1\x00"
)

// Plaintext bounds per purpose. Recovery keys are 64 hexadecimal characters;
// local-admin passwords are generated by the executor; managed material is the
// deterministic SecretMaterial protobuf.
const (
	minRecoveryKey    = 32
	maxRecoveryKey    = 128
	minLocalAdmin     = 16
	maxLocalAdmin     = 128
	maxSecretMaterial = 4608
	maxBinding        = 4096
)

// Record contains only ciphertext and nonsecret identifiers. Binding is the
// deterministic protobuf encoding of the immutable recovery target/action/slot
// or local-admin action/account. Persist that binding alongside this record;
// never reconstruct it from mutable inventory or the current device enrollment
// generation. SecretSHA256 is only stored for high-entropy device-generated
// secrets.
type Record struct {
	KeyID        string
	WrappedKey   []byte
	Ciphertext   []byte
	SecretSHA256 []byte
}

// SecretRecord is the envelope of one administrator-managed secret version.
// It deliberately has no plaintext digest: material may be low-entropy.
type SecretRecord struct {
	KeyID      string
	WrappedKey []byte
	Ciphertext []byte
}

// Custody retains distinct transport and wrapping keys loaded by the checked
// configuration boundary. Its fields cannot be serialized accidentally.
type Custody struct {
	transport   *rsa.PrivateKey
	wrapping    cipher.AEAD
	publicDER   []byte
	transportID string
	wrappingID  string
}

func (c *Custody) String() string   { return "recovery escrow custody (redacted)" }
func (c *Custody) GoString() string { return c.String() }
func (c *Custody) MarshalJSON() ([]byte, error) {
	return nil, errors.New("recovery escrow custody cannot be serialized")
}

// New validates key material before serving any action. RSA-OAEP is only the
// ingress transport; each durable record gets a separate random AES-256 key.
func New(transportPrivateKey *rsa.PrivateKey, kek []byte) (*Custody, error) {
	if transportPrivateKey == nil || transportPrivateKey.N == nil || transportPrivateKey.N.BitLen() < 3072 || transportPrivateKey.N.BitLen() > 4096 {
		return nil, errors.New("escrow: transport key must be RSA 3072 through 4096 bits")
	}
	if err := transportPrivateKey.Validate(); err != nil {
		return nil, fmt.Errorf("escrow: validate transport key: %w", err)
	}
	if len(kek) != 32 {
		return nil, errors.New("escrow: wrapping key must contain 32 bytes")
	}
	block, err := aes.NewCipher(kek)
	if err != nil {
		return nil, fmt.Errorf("escrow: create wrapping cipher: %w", err)
	}
	wrapping, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, fmt.Errorf("escrow: create wrapping AEAD: %w", err)
	}
	publicDER, err := x509.MarshalPKIXPublicKey(&transportPrivateKey.PublicKey)
	if err != nil {
		return nil, fmt.Errorf("escrow: encode transport public key: %w", err)
	}
	publicDigest := sha256.Sum256(publicDER)
	keyDigest := bindingLabel("lindm-recovery-wrapping-key-v1\x00", kek)
	return &Custody{transport: transportPrivateKey, wrapping: wrapping, publicDER: publicDER, transportID: hex.EncodeToString(publicDigest[:]), wrappingID: hex.EncodeToString(keyDigest[:])}, nil
}

// PublicKey returns a detached PKIX DER public key for a signed execution plan.
func (c *Custody) PublicKey() []byte { return bytes.Clone(c.publicDER) }
func (c *Custody) KeyID() string     { return c.transportID }

// WrappingKeyID identifies the KEK that wraps records created by this custody.
func (c *Custody) WrappingKeyID() string { return c.wrappingID }

// SealForServer encrypts a recovery key to the plan-authenticated server key.
// Binding must be the exact canonical RecoveryKeyBinding protobuf. Plaintext is
// caller-owned; the caller clears it immediately after local unlock verification.
func SealForServer(publicDER, binding, secret []byte) ([]byte, error) {
	return sealTransport(publicDER, transportDomain, binding, secret, minRecoveryKey, maxRecoveryKey)
}

// SealLocalAdminPassword encrypts an executor-generated local-admin password
// to the plan-authenticated server key. Binding must be the exact canonical
// LocalAdminPasswordBinding protobuf. The caller clears the password.
func SealLocalAdminPassword(publicDER, binding, password []byte) ([]byte, error) {
	return sealTransport(publicDER, localAdminTransportDomain, binding, password, minLocalAdmin, maxLocalAdmin)
}

// OpenAndSeal decrypts one authenticated device result and returns an envelope
// ready for durable storage. It never returns plaintext to the domain caller.
func (c *Custody) OpenAndSeal(binding, ciphertext []byte) (*Record, error) {
	return c.openAndSeal(transportDomain, storageDomain, binding, ciphertext, minRecoveryKey, maxRecoveryKey)
}

// OpenAndSealLocalAdminPassword is OpenAndSeal for the separate local-admin
// transport and storage domains.
func (c *Custody) OpenAndSealLocalAdminPassword(binding, ciphertext []byte) (*Record, error) {
	return c.openAndSeal(localAdminTransportDomain, localAdminStorageDomain, binding, ciphertext, minLocalAdmin, maxLocalAdmin)
}

// Reveal is intentionally authorization-free cryptographic machinery. Callers
// must check dedicated permission, current target scope, step-up and any required
// two-person approval, and commit the reveal audit before exposing the result.
func (c *Custody) Reveal(binding []byte, record *Record) ([]byte, error) {
	return c.revealRecord(storageDomain, binding, record, minRecoveryKey, maxRecoveryKey)
}

// RevealLocalAdminPassword is Reveal for the local-admin storage domain, with
// the same caller obligations.
func (c *Custody) RevealLocalAdminPassword(binding []byte, record *Record) ([]byte, error) {
	return c.revealRecord(localAdminStorageDomain, binding, record, minLocalAdmin, maxLocalAdmin)
}

// SealSecret envelopes one managed secret version. Binding must be the exact
// canonical binding persisted with the record. The caller clears plaintext.
func (c *Custody) SealSecret(binding, plaintext []byte) (*SecretRecord, error) {
	if len(plaintext) == 0 || len(plaintext) > maxSecretMaterial {
		return nil, errors.New("escrow: invalid secret material size")
	}
	wrapped, ciphertext, err := c.seal(secretStorageDomain, binding, plaintext)
	if err != nil {
		return nil, err
	}
	return &SecretRecord{KeyID: c.wrappingID, WrappedKey: wrapped, Ciphertext: ciphertext}, nil
}

// OpenSecret is authorization-free; callers own permission, step-up, approval
// and audit before any plaintext leaves the server. The caller clears it.
func (c *Custody) OpenSecret(binding []byte, record *SecretRecord) ([]byte, error) {
	if record == nil || record.KeyID != c.wrappingID {
		return nil, errors.New("escrow: invalid durable record")
	}
	if len(record.Ciphertext) < 1+gcmOverhead || len(record.Ciphertext) > maxSecretMaterial+gcmOverhead {
		return nil, errors.New("escrow: invalid durable record")
	}
	return c.open(secretStorageDomain, binding, record.WrappedKey, record.Ciphertext)
}

// GCM with random nonces prepends a 12-byte nonce and appends a 16-byte tag.
const gcmOverhead = 12 + 16

func sealTransport(publicDER []byte, domain string, binding, secret []byte, minSecret, maxSecret int) ([]byte, error) {
	if len(binding) == 0 || len(binding) > maxBinding || len(secret) < minSecret || len(secret) > maxSecret {
		return nil, errors.New("escrow: invalid binding or secret size")
	}
	if len(publicDER) > 1024 {
		return nil, errors.New("escrow: public key exceeds limit")
	}
	parsed, err := x509.ParsePKIXPublicKey(publicDER)
	if err != nil {
		return nil, errors.New("escrow: invalid public key")
	}
	key, ok := parsed.(*rsa.PublicKey)
	if !ok || key.N.BitLen() < 3072 || key.N.BitLen() > 4096 {
		return nil, errors.New("escrow: transport public key must be RSA 3072 through 4096 bits")
	}
	label := bindingLabel(domain, binding)
	ciphertext, err := rsa.EncryptOAEP(sha256.New(), rand.Reader, key, secret, label[:])
	if err != nil {
		return nil, fmt.Errorf("escrow: encrypt transport: %w", err)
	}
	return ciphertext, nil
}

func (c *Custody) openAndSeal(transport, storage string, binding, ciphertext []byte, minSecret, maxSecret int) (*Record, error) {
	if len(binding) == 0 || len(binding) > maxBinding || len(ciphertext) != c.transport.Size() {
		return nil, errors.New("escrow: invalid transport")
	}
	label := bindingLabel(transport, binding)
	secret, err := rsa.DecryptOAEP(sha256.New(), rand.Reader, c.transport, ciphertext, label[:])
	if err != nil {
		return nil, errors.New("escrow: transport authentication failed")
	}
	defer clear(secret)
	if len(secret) < minSecret || len(secret) > maxSecret {
		return nil, errors.New("escrow: invalid secret size")
	}
	wrapped, sealed, err := c.seal(storage, binding, secret)
	if err != nil {
		return nil, err
	}
	digest := sha256.Sum256(secret)
	return &Record{KeyID: c.wrappingID, WrappedKey: wrapped, Ciphertext: sealed, SecretSHA256: bytes.Clone(digest[:])}, nil
}

func (c *Custody) revealRecord(storage string, binding []byte, record *Record, minSecret, maxSecret int) ([]byte, error) {
	if record == nil || record.KeyID != c.wrappingID || len(record.Ciphertext) < minSecret+gcmOverhead || len(record.Ciphertext) > maxSecret+gcmOverhead || len(record.SecretSHA256) != sha256.Size {
		return nil, errors.New("escrow: invalid durable record")
	}
	secret, err := c.open(storage, binding, record.WrappedKey, record.Ciphertext)
	if err != nil {
		return nil, err
	}
	digest := sha256.Sum256(secret)
	if !bytes.Equal(digest[:], record.SecretSHA256) {
		clear(secret)
		return nil, errors.New("escrow: secret digest mismatch")
	}
	return secret, nil
}

// seal wraps a fresh random data key with the KEK; both layers use the same
// domain-separated binding AAD.
func (c *Custody) seal(domain string, binding, secret []byte) (wrapped, ciphertext []byte, err error) {
	if len(binding) == 0 || len(binding) > maxBinding {
		return nil, nil, errors.New("escrow: invalid binding")
	}
	dek := make([]byte, 32)
	if _, err := rand.Read(dek); err != nil {
		return nil, nil, fmt.Errorf("escrow: generate data key: %w", err)
	}
	defer clear(dek)
	aead, err := dataAEAD(dek)
	if err != nil {
		return nil, nil, err
	}
	aad := bindingLabel(domain, binding)
	return c.wrapping.Seal(nil, nil, dek, aad[:]), aead.Seal(nil, nil, secret, aad[:]), nil
}

func (c *Custody) open(domain string, binding, wrapped, ciphertext []byte) ([]byte, error) {
	if len(binding) == 0 || len(binding) > maxBinding || len(wrapped) != 32+c.wrapping.Overhead() {
		return nil, errors.New("escrow: invalid durable record")
	}
	aad := bindingLabel(domain, binding)
	dek, err := c.wrapping.Open(nil, nil, wrapped, aad[:])
	if err != nil {
		return nil, errors.New("escrow: data key authentication failed")
	}
	defer clear(dek)
	aead, err := dataAEAD(dek)
	if err != nil {
		return nil, err
	}
	secret, err := aead.Open(nil, nil, ciphertext, aad[:])
	if err != nil {
		return nil, errors.New("escrow: secret authentication failed")
	}
	return secret, nil
}

func dataAEAD(dek []byte) (cipher.AEAD, error) {
	block, err := aes.NewCipher(dek)
	if err != nil {
		return nil, fmt.Errorf("escrow: create data cipher: %w", err)
	}
	aead, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, fmt.Errorf("escrow: create data AEAD: %w", err)
	}
	return aead, nil
}

func bindingLabel(domain string, binding []byte) [sha256.Size]byte {
	var buffer [maxBinding + 64]byte
	n := copy(buffer[:], domain)
	n += copy(buffer[n:], binding)
	return sha256.Sum256(buffer[:n])
}
