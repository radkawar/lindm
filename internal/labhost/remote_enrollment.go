//go:build linux

package labhost

import (
	"encoding/json"
	"errors"
	"io"
	"os"
	"path/filepath"
	"syscall"
)

// enrollmentBrowser relocates the capture runner's two filesystem boundaries:
// the existing private passkey credential and the new returned screenshot tree.
// Passwords stay in protected staging, never SSH argv or returned evidence.
func (s *remoteStage) enrollmentBrowser(path string, outputs map[string]string) (string, error) {
	data, err := readEnrollmentBrowserFile(path)
	if err != nil {
		return "", err
	}
	defer clear(data)
	var config map[string]json.RawMessage
	if err := json.Unmarshal(data, &config); err != nil {
		return "", errors.New("invalid console browser configuration")
	}
	var credential, evidence string
	if json.Unmarshal(config["credentialPath"], &credential) != nil || credential == "" || json.Unmarshal(config["evidenceDirectory"], &evidence) != nil || evidence == "" {
		return "", errors.New("console browser configuration requires credentialPath and evidenceDirectory")
	}
	if _, err := os.Lstat(evidence); !errors.Is(err, os.ErrNotExist) {
		return "", errors.New("console browser evidence destination must not exist")
	}
	if prior, exists := outputs["evidence"]; exists && prior != evidence {
		return "", errors.New("console browser evidence conflicts with lane evidence output")
	}
	credentialBytes, err := readEnrollmentBrowserFile(credential)
	if err != nil {
		return "", err
	}
	defer clear(credentialBytes)
	// The browser updates its authenticator counter. Return that state to its
	// original private file, separately from the public screenshot evidence.
	credentialFile, err := os.CreateTemp(s.local, "console-credential-*.json")
	if err != nil {
		return "", err
	}
	_, writeCredentialErr := credentialFile.Write(credentialBytes)
	if err := errors.Join(writeCredentialErr, credentialFile.Close()); err != nil {
		return "", err
	}
	remoteCredential := filepath.Join(s.remote, "records", "browser-credential")
	if err := s.mkdir(filepath.Dir(remoteCredential)); err != nil {
		return "", err
	}
	if err := s.sync(credentialFile.Name(), remoteCredential); err != nil {
		return "", err
	}
	config["credentialPath"], err = json.Marshal(remoteCredential)
	if err != nil {
		return "", err
	}
	config["evidenceDirectory"], err = json.Marshal(filepath.Join(s.remote, "records", "evidence"))
	if err != nil {
		return "", err
	}
	// These are generated by the remote lane, never controller paths or secrets
	// returned to the controller through the screenshot directory.
	delete(config, "resultPath")
	delete(config, "enrollmentCommandPaths")
	delete(config, "enrollmentSecret")
	encoded, err := json.Marshal(config)
	if err != nil {
		return "", err
	}
	defer clear(encoded)
	file, err := os.CreateTemp(s.local, "console-browser-*.json")
	if err != nil {
		return "", err
	}
	_, writeErr := file.Write(encoded)
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return "", err
	}
	target, err := s.input(file.Name())
	if err != nil {
		return "", err
	}
	if err := os.Mkdir(evidence, 0700); err != nil {
		return "", err
	}
	outputs["browser-credential"] = credential
	outputs["evidence"] = evidence
	return target, nil
}

func readEnrollmentBrowserFile(path string) (_ []byte, err error) {
	file, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		return nil, err
	}
	defer func() { err = errors.Join(err, file.Close()) }()
	info, err := file.Stat()
	if err != nil {
		return nil, err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || owner.Uid != uint32(os.Geteuid()) || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || info.Size() <= 0 || info.Size() > 1<<20 {
		return nil, errors.New("console browser state must be an owned mode0600 regular file of at most 1 MiB")
	}
	data, err := io.ReadAll(io.LimitReader(file, (1<<20)+1))
	if err != nil || len(data) > 1<<20 {
		clear(data)
		return nil, errors.Join(err, errors.New("console browser state read exceeded bound"))
	}
	return data, nil
}

func returnEnrollmentCredential(source, destination string) (err error) {
	data, err := readEnrollmentBrowserFile(source)
	if err != nil {
		return err
	}
	defer clear(data)
	previous, err := readEnrollmentBrowserFile(destination)
	if err != nil {
		return err
	}
	clear(previous)
	file, err := os.CreateTemp(filepath.Dir(destination), ".lindm-browser-state-*")
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			err = errors.Join(err, os.Remove(file.Name()))
		}
	}()
	_, err = file.Write(data)
	if err == nil {
		err = file.Sync()
	}
	if err = errors.Join(err, file.Close()); err != nil {
		return err
	}
	return os.Rename(file.Name(), destination)
}
