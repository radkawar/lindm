// Pinned upstream: https://github.com/xkbcommon/libxkbcommon/tree/xkbcommon-1.11.0
// keysym-utf.c's graphical mapping table is public domain (Markus G. Kuhn).
// Keep the unmodified upstream source and LICENSE alongside this generator.
// Only data is used; no C compiler, libxkbcommon runtime, or CGo is required.
// Run from any directory: node internal/agent/desktop/keysymdata/generate.mjs
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const sourceHash = "9e010f8b544b0b9e075279e0a8569032f1fca014ff27229fd3522b395b07e833";
const source = await readFile(new URL("keysym-utf.c", import.meta.url));
if (createHash("sha256").update(source).digest("hex") !== sourceHash) {
  throw new Error(
    "keysym source SHA-256 mismatch; review the upstream update before changing the pin",
  );
}
const table = source
  .toString("utf8")
  .match(/static const struct codepair keysymtab\[\] = \{([\s\S]*?)\n\};/);
if (!table) throw new Error("upstream graphical keysym table missing");
const pairs = [
  ...table[1].matchAll(/\{\s*(0x[0-9a-f]+),\s*(false|true),\s*(0x[0-9a-f]+)\s*\}/g),
].map(([, keysym, deprecated, unicode]) => ({
  keysym: Number(keysym),
  deprecated: deprecated === "true",
  unicode: Number(unicode),
}));
if (pairs.length < 700 || pairs.some((pair, i) => i > 0 && pair.keysym <= pairs[i - 1].keysym)) {
  throw new Error("upstream graphical keysym table shape changed");
}
const header = `// Code generated by keysymdata/generate.mjs; DO NOT EDIT.\n// libxkbcommon xkbcommon-1.11.0 src/keysym-utf.c, public-domain graphical table.\n// Source SHA-256: ${sourceHash}\n// Provenance/license: internal/agent/desktop/keysymdata/{keysym-utf.c,LICENSE}.\n`;
const hex = (value) => `0x${value.toString(16).padStart(4, "0")}`;
await writeFile(
  new URL("../keysym_table_generated.go", import.meta.url),
  `${header}\npackage desktop\n\nvar legacyKeysymUnicode = [...]struct{ keysym, unicode uint16 }{\n${pairs.map((pair) => `\t{${hex(pair.keysym)}, ${hex(pair.unicode)}},`).join("\n")}\n}\n`,
);
// Match xkb_utf32_to_keysym's preference: first non-deprecated legacy mapping,
// with Latin-1 handled directly by the caller. Never include action/keypad/dead
// key conversions from xkb_keysym_to_utf32; those are not graphical symbols.
const inverse = new Map();
for (const pair of pairs) {
  if (!pair.deprecated && !inverse.has(pair.unicode)) inverse.set(pair.unicode, pair.keysym);
}
await writeFile(
  new URL("../../../../web/src/features/assistance/keysym-table.generated.ts", import.meta.url),
  `${header}\nexport const unicodeLegacyKeysyms: Readonly<Partial<Record<number, number>>> = {\n${[
    ...inverse,
  ]
    .sort(([a], [b]) => a - b)
    .map(([unicode, keysym]) => `  ${hex(unicode)}: ${hex(keysym)},`)
    .join("\n")}\n};\n`,
);
