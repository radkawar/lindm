var pamConfigStacks = []string{"common-account", "common-auth", "common-password", "common-session", "common-session-nonlogin", "postlogin-account", "postlogin-auth", "postlogin-password", "postlogin-session"}

// pam-config resolves /etc before /usr/lib and /usr/etc. Require a real manager
// symlink, not merely the generated-file comment on an administrator's stack.
func readPamConfigStack(name string) ([]byte, string, error) {
	for _, directory := range []string{"/etc/pam.d", "/usr/lib/pam.d", "/usr/etc/pam.d"} {
		path := filepath.Join(directory, name)
		_, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, "", err
		}
		link, err := os.Readlink(path)
		if err != nil || (link != name+"-pc" && link != filepath.Join(directory, name+"-pc")) {
			return nil, "", fmt.Errorf("%w: unmanaged pam-config stack %s", ErrUnsupported, name)
		}
		content, err := readNative(filepath.Join(directory, name+"-pc"), 32768)
		if err != nil {
			return nil, "", err
		}
		if !bytes.Contains(content, []byte("autogenerated by pam-config")) {
			return nil, "", ErrUnsupported
		}
		if err := pamConfigInputMatches(name, path+"-pc", content, readNative); err != nil {
			return nil, "", err
		}
		return content, path, nil
	}
	return nil, "", os.ErrNotExist
}

// pam-config resolves *-pc inputs independently of active PAM entrypoints.
// Reject an orphan higher-precedence input even when its bytes happen to match:
// that inactive file is not the active manager-owned object we observed.
func pamConfigInputMatches(name, active string, content []byte, read func(string, int64) ([]byte, error)) error {
	for _, directory := range []string{"/etc/pam.d", "/usr/lib/pam.d", "/usr/etc/pam.d"} {
		path := filepath.Join(directory, name+"-pc")
		input, err := read(path, 32768)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if path != active || !bytes.Equal(input, content) {
			return fmt.Errorf("%w: pam-config input differs from active stack", ErrUnsupported)
		}
		return nil
	}
	return ErrUnsupported
}

func inspectPamConfig(ctx context.Context, run commandRunner) (*managerState, error) {
	state := &managerState{profile: "pam-config", stacks: make(map[string][]byte)}
	graph := sha256.New()
	for _, name := range pamConfigStacks {
		content, path, err := readPamConfigStack(name)
		if err != nil {
			return nil, err
		}
		state.stacks[name] = content
		hashRecord(graph, path, content, true)
	}
	features, err := inspectStacks(state.stacks)
	if err != nil {
		return nil, err
	}
	state.features = features
	state.generation = graph.Sum(nil)
	// Bind all non-owned stack semantics across manager writes and readback.
	// pam_unix use_authtok is emitted by pam-config when quality is enabled.
	profile := sha256.New()
	for _, name := range pamConfigStacks {
		hashRecord(profile, name, []byte(strings.Join(pamLines(state.stacks[name], true), "\n")), true)
	}
	state.profileDigest = profile.Sum(nil)
	if _, err := renderPamConfig(ctx, state.stacks, nil, run); err != nil {
		return nil, err
	}
	return state, nil
}

func pamLines(content []byte, omitQuality bool) []string {
	var result []string
	for _, line := range strings.Split(string(content), "\n") {
		fields := strings.Fields(strings.SplitN(line, "#", 2)[0])
		if len(fields) == 0 || (omitQuality && slices.Contains(fields, "pam_pwquality.so")) {
			continue
		}
		if omitQuality && len(fields) >= 3 && fields[0] == "password" && fields[2] == "pam_unix.so" {
			fields = slices.DeleteFunc(fields, func(field string) bool { return field == "use_authtok" })
		}
		result = append(result, strings.Join(fields, " "))
	}
	return result
}

// renderPamConfig renders only in a private directory, validates the native
// output, and returns it for guarded publication. Never run a live manager
// command: it overwrites unrelated stacks without input compare-and-swap.
func renderPamConfig(ctx context.Context, stacks map[string][]byte, operation []string, run commandRunner) (_ map[string][]byte, err error) {
	dir, err := os.MkdirTemp("", "lindm-pam-config-")
	if err != nil {
		return nil, err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(dir)) }()
	pamDir := filepath.Join(dir, "pam.d")
	if err := os.Mkdir(pamDir, 0700); err != nil {
		return nil, err
	}
	for _, name := range pamConfigStacks {
		content, ok := stacks[name]
		if !ok {
			return nil, ErrUnsupported
		}
		if err := os.WriteFile(filepath.Join(pamDir, name+"-pc"), content, 0600); err != nil {
			return nil, err
		}
		if err := os.Symlink(name+"-pc", filepath.Join(pamDir, name)); err != nil {
			return nil, err
		}
	}
	args := []string{"--confdir", dir}
	if len(operation) == 0 {
		args = append(args, "--update")
	} else {
		args = append(args, operation...)
	}
	if _, err := run(ctx, "/usr/sbin/pam-config", args...); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	candidate := make(map[string][]byte, len(stacks))
	for _, name := range pamConfigStacks {
		content, err := readPamPreview(root, filepath.Join("pam.d", name+"-pc"))
		if err != nil {
			return nil, err
		}
		if !slices.Equal(pamLines(stacks[name], len(operation) > 0), pamLines(content, len(operation) > 0)) {
			return nil, fmt.Errorf("%w: pam-config would rewrite unmanaged stack %s", ErrUnsupported, name)
		}
		candidate[name] = content
	}
	features, err := inspectStacks(candidate)
	if err != nil {
		return nil, err
	}
	if len(operation) > 0 && slices.Contains(features, 1) != (operation[0] == "--add") {
		return nil, ErrUnsupported
	}
	return candidate, nil
}

// The root is a freshly created private directory under sticky /tmp, not a
// host configuration path. os.Root confines the native renderer's output.
func readPamPreview(root *os.Root, path string) (content []byte, err error) {
	file, err := root.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { err = errors.Join(err, file.Close()) }()
	stat, err := file.Stat()
	if err != nil {
		return nil, err
	}
	if !stat.Mode().IsRegular() || stat.Size() > 32768 {
		return nil, ErrUnsupported
	}
	content, err = io.ReadAll(io.LimitReader(file, 32769))
	if len(content) > 32768 {
		return nil, ErrUnsupported
	}
	return content, err
}

func pamConfigOperation(before, target *agentv1.ResourceOwnershipSnapshot) ([]string, error) {
	was, want := before.GetPasswordPolicy().GetEnabledFeatures(), target.GetPasswordPolicy().GetEnabledFeatures()
	for _, feature := range []agentv1.PasswordNativeFeature{2, 3} {
		if slices.Contains(was, feature) != slices.Contains(want, feature) {
			// pam-config has no faillock writer, and its pwhistory writer does
			// not emit the local-user guard required by the resource contract.
			return nil, fmt.Errorf("%w: pam-config cannot activate local-only history or faillock", ErrUnsupported)
		}
	}
	if slices.Contains(was, 1) == slices.Contains(want, 1) {
		return nil, nil
	}
	if slices.Contains(want, 1) {
		return []string{"--add", "--pwquality"}, nil
	}
	return []string{"--delete", "--pwquality"}, nil
}

func targetPamConfig(ctx context.Context, before, target *agentv1.ResourceOwnershipSnapshot, run commandRunner) error {
	operation, err := pamConfigOperation(before, target)
	if err != nil || len(operation) == 0 {
		return err
	}
	state, err := inspectPamConfig(ctx, run)
	if err != nil {
		return err
	}
	if !bytes.Equal(state.generation, before.GetPasswordPolicy().GetManagerGenerationSha256()) {
		return ErrConflict
	}
	file := nativeFile(before, 11)
	if file == nil || !file.GetState().GetExists() || !bytes.Equal(file.GetContent(), state.stacks["common-password"]) {
		return fmt.Errorf("%w: activate installer-owned /etc pam-config stacks before adoption", ErrUnsupported)
	}
	candidate, err := renderPamConfig(ctx, state.stacks, operation, run)
	if err != nil {
		return err
	}
	graph := sha256.New()
	for _, name := range pamConfigStacks {
		content, path, err := readPamConfigStack(name)
		if err != nil {
			return err
		}
		if !bytes.Equal(content, state.stacks[name]) {
			return ErrConflict
		}
		if name == "common-password" {
			// Only publish an already-active /etc manager object; never create
			// symlinks or shadow vendor entrypoints during quality adoption.
			if path != "/etc/pam.d/common-password" {
				return ErrUnsupported
			}
			content = candidate[name]
		}
		hashRecord(graph, path, content, true)
	}
	target.PasswordPolicy.ManagerGenerationSha256 = graph.Sum(nil)
	setFileContent(nativeFile(target, 11), candidate["common-password"])
	return nil
}

func pamConfigUnchanged(ctx context.Context, before *agentv1.ResourceOwnershipSnapshot, inspect func(context.Context) (*managerState, error)) error {
	state, err := inspect(ctx)
	if err != nil {
		return err
	}
	if !bytes.Equal(state.generation, before.GetPasswordPolicy().GetManagerGenerationSha256()) || !bytes.Equal(state.profileDigest, before.GetPasswordPolicy().GetManagerProfileSha256()) {
		return ErrConflict
	}
	return nil
}
