const productionSigningScope = "production-signing-tests-only"
const productionSigningGuestRoot = "/home/lindm-lab/production-signing"
const productionSigningLogLimit = 4 << 20

// VMProductionReleaseSigningOptions selects a disposable, network-enabled test
// guest. LabBinary identifies the caller's trusted matching helper, if supplied;
// this runner neither executes it on the host nor transfers it into the guest.
// WorkDir owns temporary source/VM state. Successful public evidence is retained
// in a separate private child; failed logs are retained only with DiagnosticsDir.
type VMProductionReleaseSigningOptions struct {
	Repository     string
	CacheDir       string
	WorkDir        string
	LabBinary      string
	DiagnosticsDir string
	Hardware       *VMHardwareOptions
}

type VMProductionReleaseSigningEvidence struct {
	Name   string `json:"name"`
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Size   int64  `json:"size"`
}

type VMProductionReleaseSigningStage struct {
	Name       string    `json:"name"`
	StartedAt  time.Time `json:"started_at"`
	FinishedAt time.Time `json:"finished_at"`
	Passed     bool      `json:"passed"`
}

// VMProductionReleaseSigningResult attests tests only, never a release build,
// installation/enrollment, first run or full native lifecycle qualification.
// A nonnil failed result may accompany an error; Passed requires owned cleanup.
type VMProductionReleaseSigningResult struct {
	Scope                string                               `json:"scope"`
	LifecycleQualified   bool                                 `json:"lifecycle_qualified"`
	SourceSHA256         string                               `json:"source_sha256"`
	ImageID              string                               `json:"image_id"`
	ImageSHA256          string                               `json:"image_sha256"`
	StartedAt            time.Time                            `json:"started_at"`
	FinishedAt           time.Time                            `json:"finished_at"`
	GuestNoSwap          bool                                 `json:"guest_no_swap"`
	ToolVersions         map[string]string                    `json:"tool_versions"`
	TestEvidence         []VMProductionReleaseSigningEvidence `json:"test_evidence"`
	Passed               bool                                 `json:"passed"`
	OwnedCleanupComplete bool                                 `json:"owned_cleanup_complete"`
	EvidenceDir          string                               `json:"evidence_dir,omitempty"`
	Stages               []VMProductionReleaseSigningStage    `json:"stages"`
	PublicSourceOnly     bool                                 `json:"public_source_only"`
	PristineGuestCaches  bool                                 `json:"pristine_guest_caches"`
	SourceArchiveSHA256  string                               `json:"source_archive_sha256"`
	SourceExclusions     []string                             `json:"source_exclusions"`
}

var productionSigningSourceExclusions = []string{".git/", ".cache/", ".tools/", "artifacts/", "node_modules/", "web/dist/"}

// RunVMProductionReleaseSigning runs default, integration and production_signing
// custody/release tests in a genuinely verified fresh Ubuntu 24.04 amd64 guest.
// Only public source and official public tool bytes cross the guest boundary.
// Native production keys/passphrases are generated by the tests in the safe
// guest; no host signing helper, compiler cache or npm cache is consulted.
func RunVMProductionReleaseSigning(ctx context.Context, manifest *labv1.ImageManifest, options VMProductionReleaseSigningOptions) (result *VMProductionReleaseSigningResult, err error) {
	if ctx == nil {
		return nil, errors.New("production signing tests require a context")
	}
	if err := validateManifest(manifest); err != nil {
		return nil, err
	}
	hardware, err := productionSigningHardware(manifest, options.Hardware)
	if err != nil {
		return nil, err
	}
	for _, directory := range []string{options.Repository, options.CacheDir, options.WorkDir} {
		if err := productionSigningDirectory(directory); err != nil {
			return nil, err
		}
	}
	if options.DiagnosticsDir != "" {
		if err := productionSigningDirectory(options.DiagnosticsDir); err != nil {
			return nil, err
		}
	}
	ctx, cancel := context.WithTimeout(ctx, 3*time.Hour)
	defer cancel()
	work, err := os.MkdirTemp(options.WorkDir, "production-signing-work-")
	if err != nil {
		return nil, err
	}
	result = &VMProductionReleaseSigningResult{
		Scope: productionSigningScope, ImageID: manifest.GetId(), StartedAt: time.Now().UTC(),
		ToolVersions: make(map[string]string), TestEvidence: make([]VMProductionReleaseSigningEvidence, 0),
		SourceExclusions: append([]string(nil), productionSigningSourceExclusions...),
	}
	var vm *guestVM
	var evidenceDir string
	var guestTestsStarted bool
	defer func() {
		if err != nil && options.DiagnosticsDir != "" && guestTestsStarted && vm != nil {
			diagnosticCtx, stop := context.WithTimeout(context.WithoutCancel(ctx), 30*time.Second)
			err = errors.Join(err, collectProductionSigningFailure(diagnosticCtx, vm, result))
			stop()
		}
		cleanupStarted := time.Now().UTC()
		var cleanupErr error
		if vm != nil {
			cleanupErr = vm.close()
		}
		cleanupErr = errors.Join(cleanupErr, os.RemoveAll(work))
		result.Stages = append(result.Stages, VMProductionReleaseSigningStage{Name: "owned-cleanup", StartedAt: cleanupStarted, FinishedAt: time.Now().UTC(), Passed: cleanupErr == nil})
		err = errors.Join(err, cleanupErr)
		result.OwnedCleanupComplete = cleanupErr == nil
		result.Passed = err == nil && result.GuestNoSwap && result.PristineGuestCaches && result.PublicSourceOnly
		result.FinishedAt = time.Now().UTC()
		if evidenceDir == "" {
			return
		}
		if err != nil && options.DiagnosticsDir == "" {
			err = errors.Join(err, os.RemoveAll(evidenceDir))
			result.TestEvidence = nil
			result.EvidenceDir = ""
			return
		}
		encoded, encodeErr := json.MarshalIndent(result, "", "  ")
		if encodeErr == nil {
			encodeErr = productionSigningWrite(filepath.Join(evidenceDir, "result.json"), append(encoded, '\n'))
		}
		if encodeErr != nil {
			result.Passed = false
			// A failed durable write must not leave a parseable success record.
			err = errors.Join(err, os.Remove(filepath.Join(evidenceDir, "result.json")))
			err = errors.Join(err, fmt.Errorf("retain signing test result: %w", encodeErr))
		}
	}()
	parent := options.WorkDir
	if options.DiagnosticsDir != "" {
		parent = options.DiagnosticsDir
	}
	evidenceDir, err = os.MkdirTemp(parent, "production-signing-evidence-")
	if err != nil {
		return result, err
	}
	result.EvidenceDir = evidenceDir
	manifestJSON, err := protojson.Marshal(manifest)
	if err != nil {
		return result, err
	}
	if err := productionSigningEvidence(result, "image-manifest.json", manifestJSON); err != nil {
		return result, err
	}
	started := time.Now().UTC()
	archive := filepath.Join(work, "source.tar")
	result.SourceSHA256, result.SourceArchiveSHA256, err = captureProductionSigningSource(ctx, options.Repository, archive)
	result.Stages = append(result.Stages, VMProductionReleaseSigningStage{Name: "capture-public-source", StartedAt: started, FinishedAt: time.Now().UTC(), Passed: err == nil})
	if err != nil {
		return result, err
	}
	result.PublicSourceOnly = true
	publicInputs, err := json.Marshal(map[string]any{
		"source_sha256": result.SourceSHA256, "archive_sha256": result.SourceArchiveSHA256,
		"exclusions": result.SourceExclusions, "selection": "git tracked and nonignored source; operator custody inputs refused",
		"lab_binary_transferred": false, "host_caches_transferred": false,
	})
	if err != nil {
		return result, err
	}
	if err := productionSigningEvidence(result, "public-inputs.json", publicInputs); err != nil {
		return result, err
	}
	started = time.Now().UTC()
	vm, image, startErr := newVerifiedSeededGuest(ctx, manifest, options.CacheDir, work, false, &hardware, nil)
	result.Stages = append(result.Stages, VMProductionReleaseSigningStage{Name: "vendor-verified-fresh-guest", StartedAt: started, FinishedAt: time.Now().UTC(), Passed: startErr == nil})
	if startErr != nil {
		return result, startErr
	}
	result.ImageSHA256 = image.SHA256
	imageEvidence, err := json.Marshal(map[string]any{
		"image_id": result.ImageID, "image_sha256": image.SHA256, "image_size": image.Size,
		"signing_fingerprint": image.SigningFingerprint, "primary_fingerprint": image.PrimaryFingerprint,
		"memory_mib": hardware.MemoryMiB, "cpus": hardware.CPUs, "network_enabled": true,
	})
	if err != nil {
		return result, err
	}
	if err := productionSigningEvidence(result, "verified-image.json", imageEvidence); err != nil {
		return result, err
	}
	started = time.Now().UTC()
	connectErr := vm.connect(ctx)
	result.Stages = append(result.Stages, VMProductionReleaseSigningStage{Name: "pinned-ssh-readiness", StartedAt: started, FinishedAt: time.Now().UTC(), Passed: connectErr == nil})
	if connectErr != nil {
		return result, connectErr
	}
	if _, err := productionSigningCommand(ctx, vm, result, "cloud-init", "sudo -n cloud-init status --wait", nil, 15*time.Minute); err != nil {
		return result, err
	}
	if err := productionSigningNoSwap(ctx, vm, result, "no-swap-before-setup"); err != nil {
		return result, err
	}
	if _, err := productionSigningCommand(ctx, vm, result, "native-prerequisites", "sudo -n /bin/bash -s", strings.NewReader(productionSigningNativeSetup), 30*time.Minute); err != nil {
		return result, err
	}
	file, err := openRegular(archive)
	if err != nil {
		return result, err
	}
	_, transferErr := productionSigningCommand(ctx, vm, result, "transfer-public-source", "umask 077; mkdir -- "+nativeQuote(productionSigningGuestRoot)+" && cat > "+nativeQuote(productionSigningGuestRoot+"/source.tar"), file, 10*time.Minute)
	err = errors.Join(transferErr, file.Close())
	if err != nil {
		return result, err
	}
	verifySource := "python3 - " + nativeQuote(result.SourceArchiveSHA256) + " " + nativeQuote(result.SourceSHA256)
	if _, err := productionSigningCommand(ctx, vm, result, "verify-public-source", verifySource, strings.NewReader(productionSigningVerifySource), 10*time.Minute); err != nil {
		return result, err
	}
	if _, err := productionSigningCommand(ctx, vm, result, "official-pinned-toolchains", "env -i PATH=/usr/bin:/bin HOME="+nativeQuote(productionSigningGuestRoot+"/home")+" LC_ALL=C /bin/bash -s", strings.NewReader(productionSigningInstallTools), 30*time.Minute); err != nil {
		return result, err
	}
	if _, err := productionSigningCommand(ctx, vm, result, "pristine-guest-caches", productionSigningEnvironment()+" /bin/bash -s", strings.NewReader(productionSigningPristineCaches), time.Minute); err != nil {
		return result, err
	}
	result.PristineGuestCaches = true
	versions, err := productionSigningCommand(ctx, vm, result, "exact-tool-versions", productionSigningEnvironment()+" python3 -", strings.NewReader(productionSigningToolVersions), 2*time.Minute)
	if err != nil {
		return result, err
	}
	if err := json.Unmarshal(versions.Stdout, &result.ToolVersions); err != nil {
		return result, fmt.Errorf("decode genuine guest tool versions: %w", err)
	}
	if result.ToolVersions["go"] != "go version go1.26.9 linux/amd64" || result.ToolVersions["node"] != "v24.21.0" || result.ToolVersions["npm"] == "" {
		return result, errors.New("guest tools do not match exact source pins")
	}
	if _, err := productionSigningCommand(ctx, vm, result, "web-and-license-prerequisites", productionSigningEnvironment()+" /bin/bash -s", strings.NewReader(productionSigningBuildPrerequisites), 45*time.Minute); err != nil {
		return result, err
	}
	if err := productionSigningNoSwap(ctx, vm, result, "no-swap-before-production-tests"); err != nil {
		return result, err
	}
	guestTestsStarted = true
	_, err = productionSigningCommand(ctx, vm, result, "production-integration-tests", productionSigningEnvironment()+" python3 -", strings.NewReader(productionSigningRunTests), 100*time.Minute)
	if err != nil {
		return result, err
	}
	testResult, err := productionSigningGuestEvidence(ctx, vm, result, "go-test.result.json", 64<<10)
	if err != nil {
		return result, err
	}
	var outcome struct {
		ExitCode        int  `json:"exit_code"`
		StdoutTruncated bool `json:"stdout_truncated"`
		StderrTruncated bool `json:"stderr_truncated"`
	}
	if err := json.Unmarshal(testResult, &outcome); err != nil {
		return result, err
	}
	if outcome.ExitCode != 0 || outcome.StdoutTruncated || outcome.StderrTruncated {
		result.Stages[len(result.Stages)-1].Passed = false
		return result, fmt.Errorf("production integration tests failed: exit %d, stdout_truncated=%t, stderr_truncated=%t", outcome.ExitCode, outcome.StdoutTruncated, outcome.StderrTruncated)
	}
	stdout, err := productionSigningGuestEvidence(ctx, vm, result, "go-test.stdout.jsonl", productionSigningLogLimit)
	if err != nil {
		return result, err
	}
	if _, err := productionSigningGuestEvidence(ctx, vm, result, "go-test.stderr.txt", productionSigningLogLimit); err != nil {
		return result, err
	}
	if err := productionSigningTestPasses(stdout); err != nil {
		return result, err
	}
	if err := productionSigningNoSwap(ctx, vm, result, "no-swap-after-production-tests"); err != nil {
		return result, err
	}
	return result, nil
}

func productionSigningHardware(manifest *labv1.ImageManifest, options *VMHardwareOptions) (VMHardwareOptions, error) {
	var hardware VMHardwareOptions
	if options != nil {
		hardware = *options
	}
	architecture, _, err := inspectArchitecture(manifest.GetArchitecture())
	if err != nil {
		return hardware, err
	}
	release, maintained := platform.Lookup("ubuntu-24.04")
	if !maintained || manifest.GetDistribution() != release.ID || manifest.GetVersion() != release.Version.Value || architecture != "x86_64" || manifest.GetEdition() != "server-cloudimg" {
		return hardware, errors.New("production signing tests have a maintained recipe only for Ubuntu 24.04 amd64 server-cloudimg")
	}
	if manifest.GetRepositorySnapshotManifestSha256() != "" || manifest.GetChecksumMode() != labv1.ChecksumMode_CHECKSUM_MODE_DETACHED {
		return hardware, errors.New("production signing tests require vendor-signed cloud-image checksums and live signed distro repositories, not vendor snapshots or entitlement")
	}
	for _, raw := range []string{manifest.GetImageUrl(), manifest.GetChecksumUrl(), manifest.GetSignatureUrl()} {
		url, urlErr := httpsURL(raw)
		if urlErr != nil || url.Host != "cloud-images.ubuntu.com" || !strings.HasPrefix(url.Path, "/noble/") {
			return hardware, errors.New("production signing tests require official Ubuntu noble cloud-image URLs")
		}
	}
	if manifest.GetSignerFingerprint() != "D2EB44626FDDC30B513D5BB71A5D6C4C7DB87C81" {
		return hardware, errors.New("production signing tests require the official Ubuntu cloud-image signing fingerprint")
	}
	if hardware.MemoryMiB == 0 {
		hardware.MemoryMiB = 8192
	}
	if hardware.CPUs == 0 {
		hardware.CPUs = 2
	}
	if hardware.MemoryMiB < 256 || hardware.MemoryMiB > 8192 || hardware.CPUs > 2 {
		return hardware, errors.New("production signing test guest resources must remain within 256-8192 MiB and one-two CPUs")
	}
	hardware.AllowNetwork = true
	return hardware, nil
}

func productionSigningDirectory(path string) error {
	if path == "" || !filepath.IsAbs(path) || filepath.Clean(path) != path {
		return errors.New("production signing paths must be explicit clean absolute directories")
	}
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 || info.Mode().Perm()&0022 != 0 || !ok || int(stat.Uid) != os.Geteuid() {
		return errors.New("production signing directories must be owned, nonsymlink and not group/other writable")
	}
	return nil
}

func productionSigningWrite(path string, data []byte) (err error) {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, file.Close()) }()
	if _, err := file.Write(data); err != nil {
		return err
	}
	return file.Sync()
}

func productionSigningEvidence(result *VMProductionReleaseSigningResult, name string, data []byte) error {
	path := filepath.Join(result.EvidenceDir, name)
	if err := productionSigningWrite(path, data); err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	result.TestEvidence = append(result.TestEvidence, VMProductionReleaseSigningEvidence{Name: name, Path: path, SHA256: hex.EncodeToString(sum[:]), Size: int64(len(data))})
	return nil
}

func productionSigningCommand(ctx context.Context, vm *guestVM, result *VMProductionReleaseSigningResult, name, command string, input io.Reader, timeout time.Duration) (guestCommandResult, error) {
	started := time.Now().UTC()
	observed, transportErr := vm.runResult(ctx, command, input, productionSigningLogLimit, timeout)
	err := transportErr
	if err == nil && observed.ExitCode != 0 {
		err = fmt.Errorf("production signing stage %s exited with status %d", name, observed.ExitCode)
	}
	finished := time.Now().UTC()
	result.Stages = append(result.Stages, VMProductionReleaseSigningStage{Name: name, StartedAt: started, FinishedAt: finished, Passed: err == nil})
	for _, output := range []struct {
		suffix string
		data   []byte
	}{{"stdout", observed.Stdout}, {"stderr", observed.Stderr}} {
		err = errors.Join(err, productionSigningEvidence(result, name+"."+output.suffix+".log", output.data))
	}
	metadata := map[string]any{"name": name, "command": command, "started_at": started, "finished_at": finished, "transport_complete": transportErr == nil, "exit_code": observed.ExitCode, "passed": err == nil}
	encoded, encodeErr := json.Marshal(metadata)
	if encodeErr == nil {
		encodeErr = productionSigningEvidence(result, name+".result.json", encoded)
	}
	return observed, errors.Join(err, encodeErr)
}

func productionSigningNoSwap(ctx context.Context, vm *guestVM, result *VMProductionReleaseSigningResult, name string) error {
	observed, err := productionSigningCommand(ctx, vm, result, name, "cat /proc/swaps", nil, 10*time.Second)
	if err != nil {
		result.GuestNoSwap = false
		return err
	}
	result.GuestNoSwap = productionSigningSwapHeaderOnly(observed.Stdout)
	if !result.GuestNoSwap {
		return errors.New("production signing tests refuse any active guest swap; expected /proc/swaps header only")
	}
	return nil
}

func productionSigningSwapHeaderOnly(data []byte) bool {
	lines := strings.Split(strings.TrimSpace(string(data)), "\n")
	return len(lines) == 1 && strings.Join(strings.Fields(lines[0]), " ") == "Filename Type Size Used Priority"
}

// Capture uses the existing release-source selection and digest framing. It
// refuses selected operator custody inputs rather than silently shrinking them.
// Files are read once into the private tar, and that exact stream is hashed.
func captureProductionSigningSource(ctx context.Context, repository, archive string) (sourceSHA, archiveSHA string, err error) {
	listed, err := hostCommand(ctx, repository, "git", nil, "ls-files", "--cached", "--others", "--exclude-standard", "-z")
	if err != nil {
		return "", "", err
	}
	paths, err := productionSigningSourcePaths(listed)
	if err != nil {
		return "", "", err
	}
	root, err := os.OpenRoot(repository)
	if err != nil {
		return "", "", err
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	output, err := os.OpenFile(archive, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return "", "", err
	}
	defer func() { err = errors.Join(err, output.Close()) }()
	archiveHash, sourceHash := sha256.New(), sha256.New()
	tarWriter := tar.NewWriter(io.MultiWriter(output, archiveHash))
	buffer := make([]byte, 128<<10)
	var total int64
	var goMod, nodePin bytes.Buffer
	for _, name := range paths {
		if err := ctx.Err(); err != nil {
			return "", "", err
		}
		info, err := root.Lstat(name)
		if err != nil {
			return "", "", err
		}
		total += info.Size()
		if !info.Mode().IsRegular() || info.Size() < 0 || info.Size() > 64<<20 || total > 512<<20 {
			return "", "", errors.New("production signing source requires bounded regular files without symlinks")
		}
		file, err := root.OpenFile(name, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
		if err != nil {
			return "", "", err
		}
		opened, statErr := file.Stat()
		if statErr != nil || !os.SameFile(info, opened) || info.Size() != opened.Size() || !info.ModTime().Equal(opened.ModTime()) {
			return "", "", errors.Join(errors.New("source changed while opening"), statErr, file.Close())
		}
		prefix := buffer[:min(info.Size(), 4096)]
		_, prefixErr := io.ReadFull(file, prefix)
		if prefixErr != nil || productionSigningPrivateMaterial(prefix) {
			return "", "", errors.Join(errors.New("selected source contains private custody material or unreadable input"), prefixErr, file.Close())
		}
		mode := info.Mode().Perm() & 0755
		if err := tarWriter.WriteHeader(&tar.Header{Name: filepath.ToSlash(name), Mode: int64(mode), Size: info.Size(), Typeflag: tar.TypeReg}); err != nil {
			return "", "", errors.Join(err, file.Close())
		}
		fileHash := sha256.New()
		writers := []io.Writer{tarWriter, fileHash}
		if name == "go.mod" {
			writers = append(writers, &goMod)
		}
		if name == ".node-version" {
			writers = append(writers, &nodePin)
		}
		writer := io.MultiWriter(writers...)
		written, prefixWriteErr := writer.Write(prefix)
		remaining, copyErr := io.CopyBuffer(writer, io.LimitReader(file, info.Size()-int64(len(prefix))+1), buffer)
		count := int64(written) + remaining
		copyErr = errors.Join(prefixWriteErr, copyErr)
		after, afterErr := file.Stat()
		closeErr := file.Close()
		if err := errors.Join(copyErr, afterErr, closeErr); err != nil {
			return "", "", err
		}
		if count != info.Size() || after.Size() != info.Size() || !after.ModTime().Equal(info.ModTime()) {
			return "", "", errors.New("source changed during capture")
		}
		if _, err := fmt.Fprintf(sourceHash, "%s\x00%o\x00%d\x00%s\n", name, mode, count, hex.EncodeToString(fileHash.Sum(nil))); err != nil {
			return "", "", err
		}
	}
	if !regexp.MustCompile(`(?m)^go 1\.26\.9\s*$`).Match(goMod.Bytes()) || strings.TrimSpace(nodePin.String()) != "24.21.0" {
		return "", "", errors.New("captured source must pin exact Go 1.26.9 and Node 24.21.0")
	}
	if err := tarWriter.Close(); err != nil {
		return "", "", err
	}
	if err := output.Sync(); err != nil {
		return "", "", err
	}
	return hex.EncodeToString(sourceHash.Sum(nil)), hex.EncodeToString(archiveHash.Sum(nil)), nil
}

func productionSigningSourcePaths(listed []byte) ([]string, error) {
	if len(listed) == 0 || listed[len(listed)-1] != 0 {
		return nil, errors.New("production signing source listing is empty or incomplete")
	}
	paths := strings.Split(string(listed[:len(listed)-1]), "\x00")
	if len(paths) > 100000 {
		return nil, errors.New("production signing source file count exceeds bound")
	}
	// Component ordering matches filepath.WalkDir and releasebuild.SourceDigest.
	sort.Slice(paths, func(i, j int) bool {
		a, b := paths[i], paths[j]
		for {
			partA, restA, moreA := strings.Cut(a, "/")
			partB, restB, moreB := strings.Cut(b, "/")
			if partA != partB {
				return partA < partB
			}
			if !moreA || !moreB {
				return !moreA && moreB
			}
			a, b = restA, restB
		}
	})
	kept := paths[:0]
	previous := ""
	for _, name := range paths {
		if name == previous {
			continue
		}
		previous = name
		if !filepath.IsLocal(name) || filepath.ToSlash(filepath.Clean(name)) != name {
			return nil, errors.New("invalid production signing source path")
		}
		ignored := false
		for _, prefix := range productionSigningSourceExclusions {
			if strings.HasPrefix(name, prefix) {
				ignored = true
				break
			}
		}
		if ignored {
			continue
		}
		for _, component := range strings.Split(name, "/") {
			if component == ".ssh" || component == ".gnupg" || component == "release-keys" || component == ".env" || strings.HasSuffix(component, ".p12") || strings.HasSuffix(component, ".pfx") || strings.Contains(component, "passphrase") && !strings.HasSuffix(component, ".go") {
				return nil, errors.New("selected source includes operator custody inputs; move them outside the public source capture")
			}
		}
		kept = append(kept, name)
	}
	return kept, nil
}

func productionSigningPrivateMaterial(data []byte) bool {
	prefix := bytes.TrimSpace(data)
	for _, marker := range []string{"-----BEGIN PRIVATE KEY-----", "-----BEGIN ENCRYPTED PRIVATE KEY-----", "-----BEGIN RSA PRIVATE KEY-----", "-----BEGIN EC PRIVATE KEY-----", "-----BEGIN OPENSSH PRIVATE KEY-----", "-----BEGIN PGP PRIVATE KEY BLOCK-----", "AGE-SECRET-KEY-", "(private-key", "(protected-private-key"} {
		if bytes.HasPrefix(prefix, []byte(marker)) {
			return true
		}
	}
	return false
}

