func productionSigningTestPasses(data []byte) error {
	passed := make(map[string]bool, len(productionSigningPackages))
	testsRun, testsPassed := make(map[string]bool), make(map[string]bool)
	for _, line := range bytes.Split(data, []byte{'\n'}) {
		if len(bytes.TrimSpace(line)) == 0 {
			continue
		}
		var event struct{ Action, Package, Test string }
		if err := json.Unmarshal(line, &event); err != nil {
			return fmt.Errorf("invalid genuine go test JSON: %w", err)
		}
		if event.Action == "fail" {
			return errors.New("genuine go test log contains a failure")
		}
		for _, required := range productionSigningRequiredTests[event.Package] {
			if event.Test != required && !strings.HasPrefix(event.Test, required+"/") {
				continue
			}
			if event.Action == "skip" {
				return fmt.Errorf("required production signing test skipped: %s/%s", event.Package, event.Test)
			}
			if event.Test == required {
				key := event.Package + "/" + required
				if event.Action == "run" {
					testsRun[key] = true
				}
				if event.Action == "pass" {
					testsPassed[key] = true
				}
			}
		}
		if event.Test == "" && event.Action == "pass" {
			passed[event.Package] = true
		}
	}
	for _, name := range productionSigningPackages {
		if !passed[name] {
			return fmt.Errorf("missing genuine go test package pass: %s", name)
		}
	}
	for pkg, names := range productionSigningRequiredTests {
		for _, name := range names {
			key := pkg + "/" + name
			if !testsRun[key] || !testsPassed[key] {
				return fmt.Errorf("missing executed production signing test pass: %s", key)
			}
		}
	}
	return nil
}

